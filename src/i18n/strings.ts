/** Translate and fill `{name}` placeholders. */
export const tf = (lang: Lang, key: StringKey, vars: Record<string, string | number>): string =>
  t(lang, key).replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
