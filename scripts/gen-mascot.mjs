// Generates 3 variants of a 32x32 pixel-art rubber duck, then upscales each to
// 64/96/180 PNG outputs. Plus a 32x32 blink-frame (eyes-closed) for the
// production variant. Output:
//   _design/mascot/variant_1.png ... variant_3.png  (96px previews)
//   public/mascot.png                                (96px production)
//   public/mascot-blink.png                          (96px blink frame)
//   public/mascot-32.png                             (32px nav)
//   public/mascot-180.png                            (180px favicon source)
//
// Pixel grids are hand-coded with a 5-color palette:
//   . = transparent
//   y = duck-yellow body  (#f9c47a)
//   o = darker bill/feet  (#e89c4d)
//   k = outline / pupil   (#1c1d2a)
//   w = white eye / cheek (#f4ebd9)
//   s = steam highlight   (#ffd599) — body-shade
//
// Three variants explore different silhouette ideas; the most legible is
// promoted to public/mascot.png.

