function gridToBuffer(grid) {
  const rows = grid.trim().split("\n").map((r) => r.padEnd(32, "."));
  const W = 32, H = 32;
  const buf = Buffer.alloc(W * H * 4);
  for (let y = 0; y < H; y++) {
    const row = rows[y] || ".".repeat(W);
    for (let x = 0; x < W; x++) {
      const ch = row[x] || ".";
      const px = PALETTE[ch] || PALETTE["."];
      const i = (y * W + x) * 4;
      buf[i] = px[0]; buf[i + 1] = px[1]; buf[i + 2] = px[2]; buf[i + 3] = px[3];
    }
  }
  return buf;
}

async function renderToPng(grid, size, outPath) {
  const raw = gridToBuffer(grid);
  await sharp(raw, { raw: { width: 32, height: 32, channels: 4 } })
    .resize(size, size, { kernel: "nearest" })
    .png({ compressionLevel: 9 })
    .toFile(outPath);
}

async function ensureDir(d) {
  if (!existsSync(d)) await mkdir(d, { recursive: true });
}

async function main() {
  await ensureDir(OUT_DESIGN);
  await ensureDir(OUT_PUBLIC);

  // 96px previews of each variant
  await renderToPng(V1_OPEN, 96, join(OUT_DESIGN, "variant_1.png"));
  await renderToPng(V2_OPEN, 96, join(OUT_DESIGN, "variant_2.png"));
  await renderToPng(V3_OPEN, 96, join(OUT_DESIGN, "variant_3.png"));
  console.log("[mascot] 3 variant previews written to _design/mascot/");

  // SHIP variant 2 as production (front-facing is most-recognizable as a duck)
  // Provide multiple sizes for nav (32), production (96), and favicon source (180)
  await renderToPng(V2_OPEN, 96, join(OUT_PUBLIC, "mascot.png"));
  await renderToPng(V2_BLINK, 96, join(OUT_PUBLIC, "mascot-blink.png"));
  await renderToPng(V2_OPEN, 32, join(OUT_PUBLIC, "mascot-32.png"));
  await renderToPng(V2_OPEN, 180, join(OUT_PUBLIC, "mascot-180.png"));
  console.log("[mascot] production v2 → public/mascot{,-blink,-32,-180}.png");
}

main().catch((e) => { console.error(e); process.exit(1); });
